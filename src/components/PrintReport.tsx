import { useMemo } from 'react';
import * as authModule from '../auth';

function safeOptionalAuth() {
  try {
    const mod = authModule as { useOptionalAuth?: () => ReturnType<typeof authModule.useOptionalAuth> };
    return typeof mod.useOptionalAuth === 'function' ? mod.useOptionalAuth() : null;
  } catch {
    return null;
  }
}

export type PrintOrientation = 'portrait' | 'landscape';

export interface PrintFilterItem {
  label: string;
  value: string;
}

export interface PrintReportProps {
  title: string;
  filters?: PrintFilterItem[];
  orientation?: PrintOrientation;
  onExportCsv?: () => void;
  csvLabel?: string;
  printLabel?: string;
}

function formatManilaTimestamp(date: Date): string {
  const formatted = new Intl.DateTimeFormat('en-PH', {
    timeZone: 'Asia/Manila',
    year: 'numeric',
    month: 'short',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  }).format(date);
  return `${formatted} PHT`;
}

export function PrintReport({
  title,
  filters = [],
  orientation = 'portrait',
  onExportCsv,
  csvLabel = 'Export CSV',
  printLabel = 'Print',
}: PrintReportProps) {
  const auth = safeOptionalAuth();
  const generatedBy = auth?.profile?.display_name ?? auth?.profile?.email ?? 'Admin';
  const generatedAt = useMemo(() => formatManilaTimestamp(new Date()), []);
  const activeFilters = filters.filter((f) => f.value.trim().length > 0);

  return (
    <>
      {orientation === 'landscape' ? (
        <style media="print">{`@page { size: A4 landscape; }`}</style>
      ) : null}

      <div className="print-report-actions no-print">
        <button type="button" className="button-neutral" onClick={() => window.print()}>
          {printLabel}
        </button>
        {onExportCsv ? (
          <button type="button" className="button-neutral" onClick={onExportCsv}>
            {csvLabel}
          </button>
        ) : null}
      </div>

      <header className="print-only-header">
        <div className="print-header-brand">
          <img src="/logo.png" alt="JuanderQuest" className="print-logo" />
          <div>
            <p className="print-record-kicker">JuanderQuest — official record</p>
            <p className="print-report-title">{title}</p>
          </div>
        </div>
        <div className="print-header-meta">
          <span>Generated: {generatedAt}</span>
          <span>Generated by: {generatedBy}</span>
          <span>Orientation: {orientation}</span>
        </div>
        {activeFilters.length > 0 ? (
          <div className="print-header-filters">
            <strong>Filters used:</strong>{' '}
            {activeFilters.map((f) => `${f.label}: ${f.value}`).join(' · ')}
          </div>
        ) : null}
      </header>

      <footer className="print-only-footer">
        <span>JuanderQuest — official record</span>
        <span className="print-page-number" />
      </footer>
    </>
  );
}
